CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT PRIMARY KEY CHECK (id IN (1, 2)),
    nome VARCHAR(100) NOT NULL
);
CREATE TABLE IF NOT EXISTS filmes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tmdb_id BIGINT NOT NULL CONSTRAINT uk_filme_tmdb UNIQUE,
    titulo VARCHAR(255) NOT NULL,
    sinopse TEXT,
    poster_path VARCHAR(255),
    data_lancamento DATE
);
CREATE TABLE IF NOT EXISTS filme_generos (
    filme_id BIGINT NOT NULL REFERENCES filmes(id),
    posicao INTEGER NOT NULL,
    genero VARCHAR(255) NOT NULL,
    PRIMARY KEY (filme_id, posicao)
);
CREATE TABLE IF NOT EXISTS filme_lista (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    filme_id BIGINT NOT NULL REFERENCES filmes(id),
    status VARCHAR(20) NOT NULL CHECK (status IN ('ASSISTIDO', 'QUERO_ASSISTIR')),
    favorito BOOLEAN NOT NULL DEFAULT FALSE,
    data_assistido DATE,
    CONSTRAINT uk_lista_filme UNIQUE (filme_id),
    CONSTRAINT ck_data_status CHECK ((status = 'ASSISTIDO' AND data_assistido IS NOT NULL)
        OR (status = 'QUERO_ASSISTIR' AND data_assistido IS NULL))
);
CREATE TABLE IF NOT EXISTS avaliacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    filme_id BIGINT NOT NULL REFERENCES filmes(id),
    nota NUMERIC(3,1) NOT NULL CHECK (nota BETWEEN 0 AND 10),
    comentario VARCHAR(2000),
    CONSTRAINT uk_avaliacao_usuario_filme UNIQUE (usuario_id, filme_id)
);
CREATE INDEX IF NOT EXISTS idx_avaliacoes_filme ON avaliacoes(filme_id);
